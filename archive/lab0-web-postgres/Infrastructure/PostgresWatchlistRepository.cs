using System.Text.Json;
using System.Globalization;
using Lab0.Abstractions;
using Lab0.Domain;
using Npgsql;
using NpgsqlTypes;

namespace Lab0.Infrastructure;

public sealed class PostgresWatchlistRepository(NpgsqlDataSource dataSource) : IWatchlistRepository
{
    private const string Schema = """
        CREATE TABLE IF NOT EXISTS media_categories (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name text NOT NULL
        );
        CREATE UNIQUE INDEX IF NOT EXISTS ux_media_categories_name
            ON media_categories (lower(name));

        CREATE TABLE IF NOT EXISTS media_tags (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name text NOT NULL
        );
        CREATE UNIQUE INDEX IF NOT EXISTS ux_media_tags_name
            ON media_tags (lower(name));

        CREATE TABLE IF NOT EXISTS media_items (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title text NOT NULL,
            category_id integer NOT NULL REFERENCES media_categories(id) ON DELETE RESTRICT,
            status text NOT NULL DEFAULT 'Planned' CHECK (status IN ('Planned', 'Consumed')),
            rating smallint NULL CHECK (rating IS NULL OR rating BETWEEN 1 AND 10)
        );

        CREATE TABLE IF NOT EXISTS media_item_tags (
            media_item_id integer NOT NULL REFERENCES media_items(id) ON DELETE CASCADE,
            tag_id integer NOT NULL REFERENCES media_tags(id) ON DELETE RESTRICT,
            PRIMARY KEY (media_item_id, tag_id)
        );

        CREATE TABLE IF NOT EXISTS custom_fields (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name text NOT NULL,
            field_type text NOT NULL CHECK (field_type IN ('text', 'number', 'date', 'boolean'))
        );
        CREATE UNIQUE INDEX IF NOT EXISTS ux_custom_fields_name
            ON custom_fields (lower(name));

        CREATE TABLE IF NOT EXISTS custom_field_values (
            media_item_id integer NOT NULL REFERENCES media_items(id) ON DELETE CASCADE,
            custom_field_id integer NOT NULL REFERENCES custom_fields(id) ON DELETE CASCADE,
            value_json jsonb NOT NULL,
            PRIMARY KEY (media_item_id, custom_field_id)
        );
        """;

    public async Task InitializeAsync(CancellationToken cancellationToken = default)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        await using var command = new NpgsqlCommand(Schema, connection);
        await command.ExecuteNonQueryAsync(cancellationToken);
    }

    public async Task<WatchlistSnapshot> GetWatchlistAsync(CancellationToken cancellationToken = default)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);

        var categories = new List<MediaCategory>();
        await using (var command = new NpgsqlCommand("SELECT id, name FROM media_categories ORDER BY name;", connection))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken))
        {
            while (await reader.ReadAsync(cancellationToken))
            {
                categories.Add(new MediaCategory(reader.GetString(1)) { Id = reader.GetInt32(0) });
            }
        }

        var tags = new List<MediaTag>();
        await using (var command = new NpgsqlCommand("SELECT id, name FROM media_tags ORDER BY name;", connection))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken))
        {
            while (await reader.ReadAsync(cancellationToken))
            {
                tags.Add(new MediaTag(reader.GetString(1)) { Id = reader.GetInt32(0) });
            }
        }

        var customFields = new List<CustomFieldDefinition>();
        await using (var command = new NpgsqlCommand(
            "SELECT id, name, field_type FROM custom_fields ORDER BY name;", connection))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken))
        {
            while (await reader.ReadAsync(cancellationToken))
            {
                customFields.Add(new CustomFieldDefinition(reader.GetInt32(0), reader.GetString(1), reader.GetString(2)));
            }
        }

        var entries = new Dictionary<int, EntryBuilder>();
        await using (var command = new NpgsqlCommand(
            """
            SELECT i.id, i.title, c.id, c.name, i.status, i.rating
            FROM media_items i
            JOIN media_categories c ON c.id = i.category_id
            ORDER BY i.title, i.id;
            """, connection))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken))
        {
            while (await reader.ReadAsync(cancellationToken))
            {
                var id = reader.GetInt32(0);
                entries.Add(id, new EntryBuilder(
                    id,
                    reader.GetString(1),
                    reader.GetInt32(2),
                    reader.GetString(3),
                    Enum.Parse<MediaStatus>(reader.GetString(4)),
                    reader.IsDBNull(5) ? null : reader.GetInt16(5)));
            }
        }

        await using (var command = new NpgsqlCommand(
            """
            SELECT mit.media_item_id, t.id, t.name
            FROM media_item_tags mit
            JOIN media_tags t ON t.id = mit.tag_id
            ORDER BY t.name;
            """, connection))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken))
        {
            while (await reader.ReadAsync(cancellationToken))
            {
                if (entries.TryGetValue(reader.GetInt32(0), out var entry))
                {
                    entry.TagIds.Add(reader.GetInt32(1));
                    entry.Tags.Add(reader.GetString(2));
                }
            }
        }

        await using (var command = new NpgsqlCommand(
            """
            SELECT media_item_id, custom_field_id, value_json::text
            FROM custom_field_values
            ORDER BY custom_field_id;
            """, connection))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken))
        {
            while (await reader.ReadAsync(cancellationToken))
            {
                if (entries.TryGetValue(reader.GetInt32(0), out var entry))
                {
                    using var document = JsonDocument.Parse(reader.GetString(2));
                    entry.CustomValues.Add(reader.GetInt32(1), document.RootElement.Clone());
                }
            }
        }

        return new WatchlistSnapshot(
            categories,
            tags,
            entries.Values.Select(entry => entry.Build()).ToArray(),
            customFields);
    }

    public Task CreateCategoryAsync(string name, CancellationToken cancellationToken = default) =>
        InsertNamedAsync("media_categories", name, "Category", cancellationToken);

    public Task CreateTagAsync(string name, CancellationToken cancellationToken = default) =>
        InsertNamedAsync("media_tags", name, "Tag", cancellationToken);

    public async Task<MediaEntry> AddMediaItemAsync(
        MediaItemRequest request,
        CancellationToken cancellationToken = default)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);
        try
        {
            var id = await InsertMediaItemAsync(connection, transaction, request, cancellationToken);
            await SaveRelationsAsync(connection, transaction, id, request, cancellationToken);
            await transaction.CommitAsync(cancellationToken);
            return await GetMediaEntryAsync(id, cancellationToken);
        }
        catch (PostgresException exception)
        {
            await transaction.RollbackAsync(cancellationToken);
            throw TranslateDatabaseException(exception);
        }
    }

    public async Task<MediaEntry> UpdateMediaItemAsync(
        int id,
        MediaItemRequest request,
        CancellationToken cancellationToken = default)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);
        try
        {
            await using (var command = new NpgsqlCommand(
                "UPDATE media_items SET title = @title, category_id = @category_id WHERE id = @id;",
                connection,
                transaction))
            {
                command.Parameters.AddWithValue("title", request.Title!);
                command.Parameters.AddWithValue("category_id", request.CategoryId);
                command.Parameters.AddWithValue("id", id);
                if (await command.ExecuteNonQueryAsync(cancellationToken) == 0)
                {
                    throw new KeyNotFoundException($"Media item {id} does not exist.");
                }
            }

            await SaveRelationsAsync(connection, transaction, id, request, cancellationToken);
            await transaction.CommitAsync(cancellationToken);
            return await GetMediaEntryAsync(id, cancellationToken);
        }
        catch (PostgresException exception)
        {
            await transaction.RollbackAsync(cancellationToken);
            throw TranslateDatabaseException(exception);
        }
    }

    public async Task MarkAsConsumedAsync(int id, CancellationToken cancellationToken = default)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        await using var command = new NpgsqlCommand(
            "UPDATE media_items SET status = 'Consumed' WHERE id = @id;",
            connection);
        command.Parameters.AddWithValue("id", id);
        if (await command.ExecuteNonQueryAsync(cancellationToken) == 0)
        {
            throw new KeyNotFoundException($"Media item {id} does not exist.");
        }
    }

    public async Task DeleteMediaItemAsync(int id, CancellationToken cancellationToken = default)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        await using var command = new NpgsqlCommand("DELETE FROM media_items WHERE id = @id;", connection);
        command.Parameters.AddWithValue("id", id);
        if (await command.ExecuteNonQueryAsync(cancellationToken) == 0)
        {
            throw new KeyNotFoundException($"Media item {id} does not exist.");
        }
    }

    public async Task RateMediaItemAsync(int id, int rating, CancellationToken cancellationToken = default)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        await using var command = new NpgsqlCommand(
            """
            UPDATE media_items SET rating = @rating
            WHERE id = @id AND status = 'Consumed';
            """,
            connection);
        command.Parameters.AddWithValue("rating", rating);
        command.Parameters.AddWithValue("id", id);
        if (await command.ExecuteNonQueryAsync(cancellationToken) == 0)
        {
            await ThrowMissingOrInvalidItemAsync(connection, id, cancellationToken);
        }
    }

    public async Task<CustomFieldDefinition> SaveCustomFieldAsync(
        int? id,
        CustomFieldRequest request,
        CancellationToken cancellationToken = default)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        try
        {
            if (id is null)
            {
                await using var insertCommand = new NpgsqlCommand(
                    """
                    INSERT INTO custom_fields (name, field_type)
                    VALUES (@name, @field_type)
                    RETURNING id;
                    """,
                    connection);
                insertCommand.Parameters.AddWithValue("name", request.Name!);
                insertCommand.Parameters.AddWithValue("field_type", request.Type!);
                var newId = (int)(await insertCommand.ExecuteScalarAsync(cancellationToken)
                    ?? throw new InvalidOperationException("The database did not return the new field ID."));
                return new CustomFieldDefinition(newId, request.Name!, request.Type!);
            }

            await using (var existingCommand = new NpgsqlCommand(
                "SELECT field_type FROM custom_fields WHERE id = @id;",
                connection))
            {
                existingCommand.Parameters.AddWithValue("id", id.Value);
                var existingType = await existingCommand.ExecuteScalarAsync(cancellationToken) as string
                    ?? throw new KeyNotFoundException($"Custom field {id} does not exist.");
                if (!string.Equals(existingType, request.Type, StringComparison.Ordinal))
                {
                    await using var valueCountCommand = new NpgsqlCommand(
                        "SELECT EXISTS (SELECT 1 FROM custom_field_values WHERE custom_field_id = @id);",
                        connection);
                    valueCountCommand.Parameters.AddWithValue("id", id.Value);
                    if ((bool)(await valueCountCommand.ExecuteScalarAsync(cancellationToken) ?? false))
                    {
                        throw new InvalidOperationException(
                            "A custom field's type cannot change while it has saved values. " +
                            "Delete the field and create a new one to choose another type.");
                    }
                }
            }

            await using var updateCommand = new NpgsqlCommand(
                """
                UPDATE custom_fields SET name = @name, field_type = @field_type
                WHERE id = @id;
                """,
                connection);
            updateCommand.Parameters.AddWithValue("name", request.Name!);
            updateCommand.Parameters.AddWithValue("field_type", request.Type!);
            updateCommand.Parameters.AddWithValue("id", id.Value);
            if (await updateCommand.ExecuteNonQueryAsync(cancellationToken) == 0)
            {
                throw new KeyNotFoundException($"Custom field {id} does not exist.");
            }

            return new CustomFieldDefinition(id.Value, request.Name!, request.Type!);
        }
        catch (PostgresException exception)
        {
            throw TranslateDatabaseException(exception);
        }
    }

    public async Task DeleteCustomFieldAsync(int id, CancellationToken cancellationToken = default)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        await using var command = new NpgsqlCommand("DELETE FROM custom_fields WHERE id = @id;", connection);
        command.Parameters.AddWithValue("id", id);
        if (await command.ExecuteNonQueryAsync(cancellationToken) == 0)
        {
            throw new KeyNotFoundException($"Custom field {id} does not exist.");
        }
    }

    private async Task InsertNamedAsync(
        string table,
        string name,
        string kind,
        CancellationToken cancellationToken)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        await using var command = new NpgsqlCommand($"INSERT INTO {table} (name) VALUES (@name);", connection);
        command.Parameters.AddWithValue("name", name);
        try
        {
            await command.ExecuteNonQueryAsync(cancellationToken);
        }
        catch (PostgresException exception)
        {
            if (exception.SqlState == PostgresErrorCodes.UniqueViolation)
            {
                throw new InvalidOperationException($"{kind} '{name}' already exists.");
            }

            throw;
        }
    }

    private async Task<int> InsertMediaItemAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        MediaItemRequest request,
        CancellationToken cancellationToken)
    {
        await using var command = new NpgsqlCommand(
            """
            INSERT INTO media_items (title, category_id)
            VALUES (@title, @category_id)
            RETURNING id;
            """,
            connection,
            transaction);
        command.Parameters.AddWithValue("title", request.Title!);
        command.Parameters.AddWithValue("category_id", request.CategoryId);
        return (int)(await command.ExecuteScalarAsync(cancellationToken)
            ?? throw new InvalidOperationException("The database did not return the new media ID."));
    }

    private async Task SaveRelationsAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        int id,
        MediaItemRequest request,
        CancellationToken cancellationToken)
    {
        await using (var deleteTags = new NpgsqlCommand(
            "DELETE FROM media_item_tags WHERE media_item_id = @id;",
            connection,
            transaction))
        {
            deleteTags.Parameters.AddWithValue("id", id);
            await deleteTags.ExecuteNonQueryAsync(cancellationToken);
        }

        foreach (var tagId in request.TagIds ?? [])
        {
            await using var addTag = new NpgsqlCommand(
                """
                INSERT INTO media_item_tags (media_item_id, tag_id)
                VALUES (@media_item_id, @tag_id);
                """,
                connection,
                transaction);
            addTag.Parameters.AddWithValue("media_item_id", id);
            addTag.Parameters.AddWithValue("tag_id", tagId);
            await addTag.ExecuteNonQueryAsync(cancellationToken);
        }

        await using (var deleteValues = new NpgsqlCommand(
            "DELETE FROM custom_field_values WHERE media_item_id = @id;",
            connection,
            transaction))
        {
            deleteValues.Parameters.AddWithValue("id", id);
            await deleteValues.ExecuteNonQueryAsync(cancellationToken);
        }

        var fieldTypes = await GetFieldTypesAsync(connection, transaction, cancellationToken);
        foreach (var (fieldId, value) in request.CustomValues ?? new Dictionary<int, System.Text.Json.JsonElement>())
        {
            if (!fieldTypes.TryGetValue(fieldId, out var fieldType))
            {
                throw new ArgumentException($"Custom field {fieldId} does not exist.");
            }

            if (value.ValueKind == JsonValueKind.Null)
            {
                continue;
            }

            ValidateFieldValue(fieldType, value);
            await using var addValue = new NpgsqlCommand(
                """
                INSERT INTO custom_field_values (media_item_id, custom_field_id, value_json)
                VALUES (@media_item_id, @custom_field_id, @value_json);
                """,
                connection,
                transaction);
            addValue.Parameters.AddWithValue("media_item_id", id);
            addValue.Parameters.AddWithValue("custom_field_id", fieldId);
            addValue.Parameters.Add(new NpgsqlParameter("value_json", NpgsqlDbType.Jsonb)
            {
                Value = value.GetRawText()
            });
            await addValue.ExecuteNonQueryAsync(cancellationToken);
        }
    }

    private static async Task<Dictionary<int, string>> GetFieldTypesAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        CancellationToken cancellationToken)
    {
        var types = new Dictionary<int, string>();
        await using var command = new NpgsqlCommand("SELECT id, field_type FROM custom_fields;", connection, transaction);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken))
        {
            types.Add(reader.GetInt32(0), reader.GetString(1));
        }

        return types;
    }

    private async Task<MediaEntry> GetMediaEntryAsync(int id, CancellationToken cancellationToken)
    {
        var snapshot = await GetWatchlistAsync(cancellationToken);
        return snapshot.Items.FirstOrDefault(item => item.Id == id)
            ?? throw new KeyNotFoundException($"Media item {id} does not exist.");
    }

    private static async Task ThrowMissingOrInvalidItemAsync(
        NpgsqlConnection connection,
        int id,
        CancellationToken cancellationToken)
    {
        await using var command = new NpgsqlCommand(
            "SELECT status FROM media_items WHERE id = @id;",
            connection);
        command.Parameters.AddWithValue("id", id);
        var status = await command.ExecuteScalarAsync(cancellationToken);
        if (status is null)
        {
            throw new KeyNotFoundException($"Media item {id} does not exist.");
        }

        throw new InvalidOperationException("Only consumed media can be rated.");
    }

    private static void ValidateFieldValue(string type, JsonElement value)
    {
        var valid = type switch
        {
            "text" => value.ValueKind == JsonValueKind.String,
            "number" => value.ValueKind == JsonValueKind.Number,
            "date" => value.ValueKind == JsonValueKind.String &&
                DateOnly.TryParseExact(value.GetString(), "yyyy-MM-dd", CultureInfo.InvariantCulture, DateTimeStyles.None, out _),
            "boolean" => value.ValueKind is JsonValueKind.True or JsonValueKind.False,
            _ => false
        };

        if (!valid)
        {
            throw new ArgumentException($"The value does not match the custom field type '{type}'.");
        }
    }

    private static Exception TranslateDatabaseException(PostgresException exception) =>
        exception.SqlState switch
        {
            PostgresErrorCodes.UniqueViolation =>
                new InvalidOperationException("An item with that name already exists."),
            PostgresErrorCodes.ForeignKeyViolation =>
                new ArgumentException("The selected category or tag does not exist."),
            _ => exception
        };

    private sealed class EntryBuilder(
        int id,
        string title,
        int categoryId,
        string category,
        MediaStatus status,
        int? rating)
    {
        public List<int> TagIds { get; } = [];

        public List<string> Tags { get; } = [];

        public Dictionary<int, JsonElement> CustomValues { get; } = [];

        public MediaEntry Build() => new(
            id,
            title,
            categoryId,
            category,
            status,
            rating,
            null,
            TagIds,
            Tags,
            CustomValues);
    }
}
